#!/usr/bin/env python3
# Measures every clip in assets/audio (and assets/audio/crowd) and writes src/audio/levels.js:
# the loudest 400 ms of each clip (BS.1770-style K-weighting, LUFS-ish; a clip shorter than
# 400 ms is counted over 400 ms, the way the ear integrates a transient) and its sample peak.
# The game normalises each clip to its class's reference at playback (src/audio/mix.js), so a
# re-cut or added recording only needs this re-run: python3 tools/audio_levels.py
# Needs ffmpeg and numpy.
import subprocess, sys, os, glob
import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SR = 48000

def decode(path):
    raw = subprocess.run(['ffmpeg', '-v', 'error', '-i', path, '-f', 'f32le', '-ac', '2', '-ar', str(SR), '-'],
                         capture_output=True, check=True).stdout
    return np.frombuffer(raw, dtype=np.float32).reshape(-1, 2).astype(np.float64)

def measure(a):
    n = len(a)
    fr = np.fft.rfftfreq(n, 1 / SR)
    hp = (fr / 60.0) ** 2 / (1 + (fr / 60.0) ** 2)                                    # the K curve's high-pass
    sh = 1 + (10 ** (4 / 20) - 1) * (fr / 1700.0) ** 2 / (1 + (fr / 1700.0) ** 2)        # and its +4 dB presence shelf
    k = np.fft.irfft(np.fft.rfft(a, axis=0) * (hp * sh)[:, None], n=n, axis=0)
    p = (k ** 2).sum(1)
    w = int(0.4 * SR)
    if n > w:
        c = np.concatenate([[0], np.cumsum(p)])
        m = ((c[w:] - c[:-w]) / w).max()
    else:
        m = p.sum() / w
    return round(float(-0.691 + 10 * np.log10(max(m, 1e-12))), 1), round(float(20 * np.log10(max(np.abs(a).max(), 1e-9))), 1)

def main():
    rows = []
    for f in sorted(glob.glob(os.path.join(ROOT, 'assets/audio/*.ogg')) + glob.glob(os.path.join(ROOT, 'assets/audio/*.wav'))
                    + glob.glob(os.path.join(ROOT, 'assets/audio/crowd/*.ogg'))):
        name = os.path.splitext(os.path.basename(f))[0]
        m, pk = measure(decode(f))
        rows.append((name, m, pk))
        print(f'{name:28s} {m:6.1f} LUFS(M400) {pk:6.1f} dBFS', file=sys.stderr)
    out = ['// Generated by tools/audio_levels.py: each clip\'s loudest 400 ms (K-weighted, LUFS-ish) and its',
           '// sample peak (dBFS). src/audio/mix.js normalises a clip to its class\'s reference from these.',
           'export const LEVELS = {']
    for name, m, pk in rows: out.append(f"  {name}: [{m}, {pk}],")
    out.append('};')
    open(os.path.join(ROOT, 'src/audio/levels.js'), 'w').write('\n'.join(out) + '\n')

if __name__ == '__main__':
    main()
